"""Research report, model card, CSV/HTML/PDF exports from ACTUAL project results."""
from __future__ import annotations

import html
import io
from datetime import datetime

import pandas as pd

import config
from src.models import predict


def _fmt(v, d=3):
    return "n/a" if v is None or v != v else f"{v:.{d}f}"


def collect() -> dict:
    metrics, meta = predict.load_metrics(), predict.load_metadata()
    if not metrics or not meta:
        raise predict.ModelNotTrained("Train a model first: python train_model.py")
    return {"metrics": metrics, "meta": meta}


def comparison_table(metrics: dict) -> pd.DataFrame:
    rows = []
    for rank, n in enumerate(metrics["ranking"], 1):
        m = metrics["models"][n]["metrics"]
        rows.append({"rank": rank, "model": n, "cv_roc_auc": m["cv_roc_auc_mean"], "cv_std": m["cv_roc_auc_std"],
                     "test_roc_auc": m["roc_auc"], "test_pr_auc": m["pr_auc"], "accuracy": m["accuracy"],
                     "precision": m["precision"], "recall": m["recall"], "f1": m["f1"], "brier": m["brier"],
                     "train_s": m["train_seconds"], "infer_ms_per_row": m["inference_ms_per_row"]})
    return pd.DataFrame(rows)


def _sections(ctx: dict, importance: pd.DataFrame | None, imp_method: str | None) -> list[tuple[str, list[str]]]:
    m, meta = ctx["metrics"], ctx["meta"]
    q, ds, sch = meta["quality"], meta["dataset"], meta["schema"]
    fin = m["final_calibrated"]["metrics"]
    synth = ds.get("synthetic")
    s = []
    s.append(("1. Project overview", [
        f"Title: {config.ACADEMIC_TITLE}.",
        f"Application: {config.APP_NAME} — {config.TAGLINE}. Executed by {' and '.join(config.EXECUTORS)}.",
        f"Generated: {datetime.now():%Y-%m-%d %H:%M}. Model version: {meta['version']}.",
        "Intended use: educational research into how academic and socioeconomic factors relate to placement outcomes."]))
    s.append(("2. Dataset description and provenance", [
        f"File: {ds.get('file')} — {ds.get('rows_used')} rows used after cleaning (target: '{ds.get('target')}').",
        ("WARNING: this dataset is SYNTHETIC demo data generated by the project. All relationships, including "
         "socioeconomic effects, are developer assumptions. Metrics below are NOT real-world validation."
         if synth else "Dataset supplied by the project owner in data/raw/. Verify provenance and consent before publication."),
        f"Rows read: {q['rows']}; duplicates: {q['duplicates']}; missing cells: {q['missing_cells']}.",
        f"Class counts — placed: {q['class_counts']['placed']}, not placed: {q['class_counts']['not_placed']} "
        f"(placement rate {q['placement_rate']:.1%}; imbalance ratio {q['imbalance_ratio']:.2f})."]))
    s.append(("3. Features", [
        f"Academic/skills features: {', '.join(sch['academic']) or 'none'}.",
        f"Socioeconomic features: {', '.join(sch['socioeconomic']) or 'none present in the dataset (limitation)'}.",
        f"Audit-only (never predictors): {', '.join(sch['audit_only']) or 'none'}.",
        f"Excluded identifiers/high-cardinality: {', '.join(sch['dropped']) or 'none'}."]))
    s.append(("4. Preprocessing and statistical methods", [
        "Numeric: median imputation (+ standardisation for scale-sensitive models). Categorical: most-frequent imputation + one-hot.",
        "All preprocessing sits inside scikit-learn Pipelines, so it is fit on training folds only (no leakage).",
        "Statistical tests: Welch t-test or Mann–Whitney U (numeric); chi-square or Fisher exact (categorical); "
        "effect sizes (Cohen's d, rank-biserial r, Cramér's V); Benjamini–Hochberg correction; Wilson CIs; "
        "multivariable logistic regression (odds ratios). Association is not causation."]))
    s.append(("5. Model training methodology", [
        f"Stratified {int((1 - m['split']['test_size']) * 100)}/{int(m['split']['test_size'] * 100)} train/test split (seed {m['split']['seed']}); "
        f"train n={m['split']['train']}, test n={m['split']['test']}.",
        f"Selection: {m['selection_metric']}. Selected model: {m['selected']}.",
        "Probability calibration: sigmoid (Platt) via 5-fold CalibratedClassifierCV on the training split.",
        f"Models trained: {', '.join(meta['models_trained'])}. "
        f"Unavailable (optional libs not installed): {', '.join(meta['models_skipped_unavailable']) or 'none'}."]))
    s.append(("6. Evaluation results (held-out test set, calibrated selected model)", [
        f"Accuracy {_fmt(fin['accuracy'])}; precision {_fmt(fin['precision'])}; recall {_fmt(fin['recall'])}; "
        f"F1 {_fmt(fin['f1'])}; ROC-AUC {_fmt(fin['roc_auc'])}; PR-AUC {_fmt(fin['pr_auc'])}; Brier {_fmt(fin['brier'])}.",
        "Metrics come from a single test split and carry sampling uncertainty; accuracy depends on the 0.5 threshold and class balance."]))
    if importance is not None:
        top = ", ".join(f"{r.feature} ({r.importance:.3f})" for r in importance.head(6).itertuples())
        s.append(("7. Explainability findings", [f"Method: {imp_method}.", f"Top features: {top}.",
                                                 "Importances describe how the model uses features, not causal effects."]))
    s.append(("8. Limitations", [
        "Single dataset, single split; no external validation." + (" Data are synthetic." if synth else ""),
        "Socioeconomic coverage is limited to the columns actually present in the data.",
        "Predictions are probabilities, not guarantees. Fairness has been checked only on audit columns available."]))
    s.append(("9. Responsible AI", [
        "Protected attributes are excluded from predictors and used only for subgroup auditing.",
        "This system supports educational research and must not be the sole basis for admission, hiring or any individual decision."]))
    s.append(("10. Reproducibility", [
        f"Seed {config.RANDOM_STATE}; CV folds {config.CV_FOLDS}; tracking backend: {meta['tracking_backend']}.",
        "Reproduce with: python train_model.py --fresh"]))
    return s


def build_html(importance=None, imp_method=None, comp: pd.DataFrame | None = None) -> str:
    ctx = collect()
    sec = _sections(ctx, importance, imp_method)
    comp = comparison_table(ctx["metrics"]) if comp is None else comp
    css = ("body{font-family:Segoe UI,Arial,sans-serif;background:#0b1020;color:#e5e7ff;max-width:900px;margin:30px auto;"
           "line-height:1.55}h1{color:#22d3ee}h2{color:#a855f7;border-bottom:1px solid #334;padding-bottom:4px}"
           "table{border-collapse:collapse;width:100%;font-size:12px}td,th{border:1px solid #334;padding:4px 6px}"
           "th{background:#1b2150}.warn{color:#fbbf24}")
    body = [f"<h1>{html.escape(config.ACADEMIC_TITLE)}</h1><p>{config.APP_NAME} — {config.TAGLINE}</p>"]
    for title, lines in sec:
        body.append(f"<h2>{html.escape(title)}</h2>")
        for ln in lines:
            cls = " class='warn'" if ln.startswith("WARNING") else ""
            body.append(f"<p{cls}>{html.escape(ln)}</p>")
        if title.startswith("6."):
            body.append(comp.round(4).to_html(index=False))
    return f"<!doctype html><html><head><meta charset='utf-8'><title>Research Report</title><style>{css}</style></head><body>{''.join(body)}</body></html>"


def build_model_card(importance=None, imp_method=None) -> str:
    ctx = collect()
    m, meta = ctx["metrics"], ctx["meta"]
    fin = m["final_calibrated"]["metrics"]
    synth = meta["dataset"].get("synthetic")
    lines = [f"# Model Card — {m['selected']} (calibrated)", "",
             f"**Project:** {config.ACADEMIC_TITLE}", f"**Version:** {meta['version']}  ·  **Trained:** {meta['trained_at']}", "",
             "## Intended use", "Educational research on academic and socioeconomic correlates of placement. "
             "Not for hiring, admission or other consequential individual decisions.", "",
             "## Data", f"Source file: `{meta['dataset'].get('file')}` ({meta['dataset'].get('rows_used')} rows)."
             + (" **SYNTHETIC demo data — not real students.**" if synth else ""),
             f"Predictors: {', '.join(meta['schema']['features'])}.",
             f"Audit-only (not predictors): {', '.join(meta['schema']['audit_only']) or 'none'}.", "",
             "## Performance (held-out test set)",
             f"ROC-AUC {_fmt(fin['roc_auc'])} · PR-AUC {_fmt(fin['pr_auc'])} · Accuracy {_fmt(fin['accuracy'])} · "
             f"F1 {_fmt(fin['f1'])} · Brier {_fmt(fin['brier'])}", ""]
    if importance is not None:
        lines += ["## Explainability", f"{imp_method}. Top: " + ", ".join(importance.head(5)["feature"]) + ".", ""]
    lines += ["## Limitations", "- Single split, no external validation." + (" Synthetic data." if synth else ""),
              "- Probabilities are calibrated on training data only; they are not guarantees.",
              "- Associations learned by the model are not causal.", "",
              "## Ethical considerations",
              "- Protected attributes excluded from predictors; audited only at subgroup level.",
              "- Keep a human in the loop; do not use as the sole basis for any decision."]
    return "\n".join(lines)


def build_pdf(importance=None, imp_method=None) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
    ctx = collect()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=config.ACADEMIC_TITLE)
    st = getSampleStyleSheet()
    story = [Paragraph(html.escape(config.ACADEMIC_TITLE), st["Title"]),
             Paragraph(f"{config.APP_NAME} — {config.TAGLINE}", st["Normal"]), Spacer(1, 12)]
    for title, lines in _sections(ctx, importance, imp_method):
        story.append(Paragraph(html.escape(title), st["Heading2"]))
        for ln in lines:
            story.append(Paragraph(html.escape(ln), st["BodyText"]))
    doc.build(story)
    return buf.getvalue()

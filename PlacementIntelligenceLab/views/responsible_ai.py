"""Responsible AI: provenance, limitations, fairness audit, leakage checks."""
import numpy as np
import pandas as pd
import plotly.express as px
import streamlit as st

from src.analytics import viz3d
from src.data import loader
from src.models.train import safe_metrics
from src.utils import ui
import config


def _fairness(test: pd.DataFrame, col: str, thr: float = 0.5) -> pd.DataFrame:
    rows = []
    for g, d in test.groupby(col):
        n = len(d)
        pred = (d["proba"] >= thr)
        m = safe_metrics(d["y_true"], d["proba"], thr)
        pos = d["y_true"] == 1
        rows.append({"group": g, "n": n, "actual_placement_rate": d["y_true"].mean(),
                     "predicted_positive_rate": pred.mean(),
                     "TPR (recall)": pred[pos].mean() if pos.any() else np.nan,
                     "FPR": pred[~pos].mean() if (~pos).any() else np.nan,
                     "ROC-AUC": m["roc_auc"], "reliable": n >= 30})
    return pd.DataFrame(rows)


def render():
    c = ui.ctx()
    ui.page_header("Responsible AI", "Provenance, limitations, fairness auditing and leakage checks.")
    ui.synthetic_banner(c)
    schema = c["schema"]
    t1, t2, t3, t4, t5 = st.tabs(["Provenance & features", "Data quality", "Fairness audit", "Leakage checks", "Usage guidance"])
    with t1:
        st.markdown(f"**Dataset:** `{c['info']['file']}` — " + ("SYNTHETIC demo data generated by this project."
                    if c["info"]["synthetic"] else "user-supplied data (verify provenance and consent)."))
        st.markdown(f"**Academic/skills predictors:** {', '.join(schema['academic']) or 'none'}")
        st.markdown(f"**Socioeconomic predictors:** {', '.join(schema['socioeconomic']) or 'none present (limitation)'}")
        st.markdown(f"**Audit-only attributes (never predictors):** {', '.join(schema['audit_only']) or 'none in this dataset'}")
        st.markdown(f"**Excluded identifiers / high-cardinality:** {', '.join(schema['dropped']) or 'none'}")
        st.markdown("**Known limitations**\n- Single dataset and split; no external validation.\n"
                    "- Socioeconomic coverage only as good as the supplied columns.\n"
                    "- Predictions are probabilities; calibration was estimated on the training split.\n"
                    "- Explanations (SHAP / permutation) show association, not causation.")
    with t2:
        q = loader.validate_dataset(c["df"], schema["target"])
        ui.tiles([("Rows", str(q["rows"]), ""), ("Duplicates", str(q["duplicates"]), "removed at training"),
                  ("Missing cells", str(q["missing_cells"]), "imputed in pipeline"),
                  ("Imbalance ratio", f"{q['imbalance_ratio']:.2f}", "majority : minority")])
        st.json(q["missing_by_column"] or {"missing": "none"})
    with t3:
        if not ui.require_model(c):
            pass
        elif not schema["audit_only"]:
            st.info("No protected/audit columns (e.g. gender, caste) exist in this dataset, so no subgroup fairness audit "
                    "can be run. Add such a column to data/raw/ to enable audit-only analysis; it will still be excluded "
                    "from the predictors.")
        else:
            test = pd.read_csv(config.TEST_PRED_PATH)
            col = st.selectbox("Audit attribute", [x for x in schema["audit_only"] if x in test.columns])
            thr = st.slider("Threshold", 0.1, 0.9, 0.5, 0.05, key="fair_thr")
            f = _fairness(test, col, thr)
            st.dataframe(f.round(3), width="stretch", hide_index=True)
            m = f.melt(id_vars="group", value_vars=["actual_placement_rate", "predicted_positive_rate", "TPR (recall)", "FPR"])
            st.plotly_chart(viz3d.style(px.bar(m, x="variable", y="value", color="group", barmode="group"), 360,
                                        "Subgroup rates (held-out test set)"), width="stretch")
            if (~f["reliable"]).any():
                st.warning("Groups with n < 30 are shown for transparency but are too small to draw conclusions.")
            gap = f["predicted_positive_rate"].max() - f["predicted_positive_rate"].min()
            tpr_gap = f["TPR (recall)"].max() - f["TPR (recall)"].min()
            st.info(f"Largest gap in predicted-positive rate: {gap:.3f}; in true-positive rate: {tpr_gap:.3f}. "
                    "Gaps can arise from genuine differences in the data and are not proof of bias or fairness. "
                    "High overall accuracy does not mean the model is unbiased.")
    with t4:
        checks = []
        checks.append(("Target column excluded from predictors", schema["target"] not in schema["features"]))
        checks.append(("Protected attributes excluded from predictors", not set(schema["audit_only"]) & set(schema["features"])))
        checks.append(("Identifier-like columns excluded", not set(schema["dropped"]) & set(schema["features"])))
        checks.append(("Preprocessing fit inside pipelines (train folds only)", True))
        if c["trained"]:
            test = pd.read_csv(config.TEST_PRED_PATH)
            ref = pd.read_csv(config.TRAIN_REF_PATH)
            key = schema["features"]
            overlap = int(test[key].merge(ref[key].drop_duplicates(), on=key).shape[0])
            checks.append((f"Exact feature-row overlap between train and test: {overlap} rows (identical profiles can occur naturally)", overlap == 0))
            corr = c["df"][list(schema["numeric"])].assign(y=loader.encode_target(c["df"][schema["target"]])).corr()["y"].drop("y").abs()
            checks.append((f"No single numeric feature is almost perfectly correlated with the target (max |r| = {corr.max():.2f})", bool(corr.max() < 0.9)))
        for name, ok in checks:
            st.markdown(f"{'✅' if ok else '⚠️'} {name}")
    with t5:
        st.markdown("- Use only for **educational research** and self-reflection.\n"
                    "- Never use as the **sole basis** for hiring, admission or any individual decision.\n"
                    "- Keep a human in the loop and explain results as probabilities with uncertainty.\n"
                    "- Do not add protected attributes as predictors. Audit them separately and with consent.\n"
                    "- Re-train and re-validate when the student population or placement market changes.")
